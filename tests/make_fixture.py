"""Generate a SMALL SYNTHETIC dataset in MovieLens CSV format.

!! TEST-ONLY. This exists so the code can be exercised end to end without
!! network access. It is NOT MovieLens, no result computed from it is ever
!! reported in the README, and the app never uses it unless you point it there.
"""
from pathlib import Path

import numpy as np
import pandas as pd

GENRES = ["Action", "Comedy", "Drama", "Sci-Fi", "Romance", "Thriller", "Animation", "Horror"]


def make_fixture(out_dir: Path, n_users: int = 120, n_movies: int = 300, seed: int = 0,
                 ratings_per_user: tuple = (15, 60)) -> Path:
    rng = np.random.default_rng(seed)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    movies = []
    for m in range(1, n_movies + 1):
        gs = list(rng.choice(GENRES, size=rng.integers(1, 4), replace=False))
        title = f"Test Movie {m}" + (", The" if m % 7 == 0 else "")
        if m % 7 == 0:
            title = f"Test Movie {m}, The"
        movies.append({"movieId": m * 3, "title": f"{title} ({1960 + m % 60})",
                       "genres": "|".join(gs) if m % 50 else "(no genres listed)"})
    movies = pd.DataFrame(movies)

    # latent-factor ratings: users and movies share 4 hidden taste dimensions
    k = 4
    U, V = rng.normal(size=(n_users, k)), rng.normal(size=(n_movies, k))
    pop = rng.pareto(1.2, n_movies) + 1
    pop = pop / pop.sum()
    rows = []
    for u in range(n_users):
        n_r = int(rng.integers(*ratings_per_user))
        chosen = rng.choice(n_movies, size=n_r, replace=False, p=pop)
        t0 = 1_000_000_000 + int(rng.integers(0, 10_000_000))
        for j, m in enumerate(chosen):
            raw = 3.4 + 0.6 * U[u] @ V[m] + rng.normal(0, 0.4)
            rows.append({"userId": u + 1, "movieId": (m + 1) * 3,
                         "rating": float(np.clip(np.round(raw * 2) / 2, 0.5, 5.0)),
                         "timestamp": t0 + j * 1000})
    ratings = pd.DataFrame(rows)
    # inject dirt that cleaning must handle
    dirt = pd.concat([ratings.iloc[:3].assign(rating=9.0),           # out of range
                      ratings.iloc[3:6].assign(movieId=999_999),     # unknown movie
                      ratings.iloc[6:9]])                            # exact duplicates
    ratings = pd.concat([ratings, dirt], ignore_index=True)

    unique_pairs = ratings.drop_duplicates(["userId", "movieId"])
    tags = unique_pairs.sample(min(200, len(unique_pairs)), random_state=seed)[
        ["userId", "movieId"]].assign(tag=lambda d: rng.choice(["funny", "twisty", "dark", "slow"], len(d)),
                                      timestamp=1_000_000_000)
    links = pd.DataFrame({"movieId": movies["movieId"], "imdbId": 100000 + movies["movieId"],
                          "tmdbId": movies["movieId"]})

    (out_dir / "SYNTHETIC_DATA.txt").write_text(
        "Synthetic test data generated by tests/make_fixture.py. NOT MovieLens.\n")
    ratings.to_csv(out_dir / "ratings.csv", index=False)
    movies.to_csv(out_dir / "movies.csv", index=False)
    tags.to_csv(out_dir / "tags.csv", index=False)
    links.to_csv(out_dir / "links.csv", index=False)
    return out_dir
